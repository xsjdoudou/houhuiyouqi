function calculate(answers) {
  if (!Array.isArray(answers) || answers.length !== questions.length ||
      !Array.from(answers).every(value => Number.isInteger(value) && value >= 0 && value <= 3)) return null
  const scores = [0, 0, 0]
  const first = [null, null, null]
  questions.forEach((question, index) => {
    scores[question.axis] += [2, 1, -1, -2][answers[index]]
    if (first[question.axis] === null) first[question.axis] = answers[index] < 2 ? 0 : 1
  })
  // 每个维度平分时使用该维度的第一道题，确保结果唯一。
  const key = scores.map((score, axis) => score === 0 ? first[axis] : score > 0 ? 0 : 1).join('')
  return profiles[key]
}
